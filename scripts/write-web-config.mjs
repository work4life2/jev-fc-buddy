// Writes web/config.js for an off-origin deployment of the play page (Vercel): JEV_API_BASE names
// the API server the page should talk to. Without JEV_API_BASE the committed default (same origin)
// is left untouched, so local builds never dirty the working tree.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const base = (process.env.JEV_API_BASE ?? "").trim().replace(/\/+$/, "");
if (!base) {
  console.log("JEV_API_BASE not set: web/config.js left as committed (same-origin API)");
  process.exit(0);
}
if (!/^https?:\/\/[^\s"']+$/.test(base)) {
  console.error(`JEV_API_BASE is not a plain http(s) URL: ${base}`);
  process.exit(1);
}
const out = path.join(root, "web", "config.js");
fs.writeFileSync(
  out,
  `// Generated by scripts/write-web-config.mjs at build time: the play page is hosted away from the API server.\nwindow.JEV_API_BASE = ${JSON.stringify(base)};\n`,
);
console.log(`wrote web/config.js → API at ${base}`);
